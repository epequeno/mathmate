#!/usr/bin/env node
// ─── check-ts-types.mjs ───────────────────────────────────────────────
// CI guard: verifies that generated TS types in src/lib/types-generated/
// exist and have the ts-rs header.
//
// A full freshness check requires running cargo test --features export-types,
// which is too slow for prebuild.  Use `npm run generate:ts-types` to
// regenerate and commit manually.

import { readFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const outDir = resolve(root, "src/lib/types-generated");

const required = ["session.ts", "config.ts", "memory.ts", "tool.ts", "index.ts"];
let ok = true;

for (const name of required) {
  const path = resolve(outDir, name);
  if (!existsSync(path)) {
    console.log(`ERROR: Missing generated type file: src/lib/types-generated/${name}`);
    ok = false;
    continue;
  }
  const content = readFileSync(path, "utf-8");
  if (!content.includes("generated by [ts-rs]") && name !== "index.ts") {
    console.log(`WARN: src/lib/types-generated/${name} missing ts-rs header (was it hand-edited?)`);
  }
}

if (!ok) {
  console.log("\nRun: npm run generate:ts-types");
  process.exit(1);
}

console.log("OK: generated TS types present");
